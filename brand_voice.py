"""
Brand voice — the speaking style used when writing scripts.

Scripts must sound like the creator actually talks on camera, not like an
AI-generated text. Customize the block below to match your own brand voice,
or drive it from configuration.
"""

BRAND_VOICE = """
BRAND VOICE (mandatory for every script):

SIGNATURE ANGLE (the hook that only this creator can use):
Every script should open, within the first 3 seconds, with the creator's
unique personal angle — the one thing competitors can't copy. Define it once
for your brand (a background, an unusual credential, a bold claim backed by
results) and reuse it in the hook. Vary the wording, but keep the angle up front.

HOW THE CREATOR TALKS:
- Short sentences, 5-10 words. No long, subordinate-clause constructions.
- Conversational, like explaining something to a friend.
- Casual connectors: "look", "basically", "here's the thing", "okay".
- "let me show you", "check this out", "for example".
- No bureaucratic language. Not "implement a deployment", but "ship a bot".
- No AI clichés: NOT "in a world where technology...", NOT "let's dive in".
- No dashes in enumerations — that reads as AI.

HOW THE CREATOR DOES NOT TALK (banned in scripts):
- "Friends" / "Dear friends" / "Esteemed viewers"
- "Let's break it down" / "Let's talk about"
- "In today's world" / "In the age of technology"
- "It's no secret that" / "As we all know"
- "Subscribe to our channel" (it's a personal brand, not a "we")
- "Would you like to know" / "Have you ever wondered"
- Long sentences with participial constructions
- Bullet lists or dash enumerations (that's the AI tell)
- "Result:" / "Conclusion:" / "Takeaway:" — the creator doesn't talk in headers

TONE:
- Confident but not arrogant
- Someone who actually does the work, not a lecturer
- Energetic, fast pace
- Direct — says it like it is, no wrapping
- A little bold
- Not a hype-seller — no "millions in a week" promises
- Not a nerd — no jargon dumps, explains the business result

EXAMPLE ON-CAMERA LINES (adapt to your niche):
- "Look. This business owner spent 4 hours a day answering DMs. I built a bot in a day. Now it's zero minutes."
- "You know how much a bot costs? From X. A hired employee costs Y a month. And the bot doesn't get sick, doesn't show up late."
- "Watch. I press one button, the bot scrapes, writes, and publishes on its own. No human needed."

ANTI-EXAMPLES (do NOT write like this):
BAD:  "In today's world, business process automation is becoming a key success factor."
GOOD: "Look, while you're answering messages by hand, your competitor already deployed a bot."

BAD:  "Would you like to learn how to save a fortune every month?"
GOOD: "That's how much a non-automated business loses every month. Let me show you why."

BAD:  "Subscribe to our channel and get a free webinar!"
GOOD: "Free checklist in the bio — grab it."
"""
